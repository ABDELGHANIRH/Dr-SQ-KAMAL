let currentLang = 'fr';

document.addEventListener('DOMContentLoaded', () => {
    // --- Language Toggle Logic ---
    const langToggleBtn = document.getElementById('lang-toggle');
    
    function setLanguage(lang) {
        currentLang = lang;
        document.documentElement.lang = lang;
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
        
        // Update texts
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                el.innerHTML = translations[lang][key];
            }
        });
        
        // Toggle Button text
        langToggleBtn.textContent = lang === 'fr' ? 'عربي' : 'Français';
        
        // Regenerate Calendar for new language
        generateCalendar();
    }

    langToggleBtn.addEventListener('click', () => {
        setLanguage(currentLang === 'fr' ? 'ar' : 'fr');
    });

    // --- Calendar Generation ---
    const dateScroll = document.getElementById('date-scroll');
    const today = new Date();
    
    const daysFr = ['Dim', 'Lun', 'Mar', 'Mer', 'Jeu', 'Ven', 'Sam'];
    const monthsFr = ['Jan', 'Fév', 'Mar', 'Avr', 'Mai', 'Juin', 'Juil', 'Aoû', 'Sep', 'Oct', 'Nov', 'Déc'];
    
    const daysAr = ['الأحد', 'الإثنين', 'الثلاثاء', 'الأربعاء', 'الخميس', 'الجمعة', 'السبت'];
    const monthsAr = ['يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو', 'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر'];

    let selectedDate = null;
    let selectedTime = null;

    function generateCalendar() {
        dateScroll.innerHTML = ''; // Clear existing
        const days = currentLang === 'ar' ? daysAr : daysFr;
        const months = currentLang === 'ar' ? monthsAr : monthsFr;
        
        // If language changed after selection, clear selection
        selectedDate = null;
        selectedTime = null;
        document.getElementById('time-group').style.opacity = '0.5';
        document.getElementById('time-group').style.pointerEvents = 'none';
        document.querySelectorAll('.time-slot').forEach(t => t.classList.remove('active'));

        for (let i = 1; i <= 14; i++) {
            const d = new Date(today);
            d.setDate(today.getDate() + i);
            if (d.getDay() === 0) continue; // Skip Sundays

            const btn = document.createElement('button');
            btn.type = 'button';
            btn.className = 'date-btn';
            
            const dayName = days[d.getDay()];
            const dateNum = d.getDate();
            const monthName = months[d.getMonth()];

            btn.innerHTML = `
                <span class="date-day">${dayName}</span>
                <span class="date-num">${dateNum}</span>
                <span class="date-month">${monthName}</span>
            `;

            btn.addEventListener('click', () => {
                document.querySelectorAll('.date-btn').forEach(b => b.classList.remove('active'));
                btn.classList.add('active');
                selectedDate = d;
                
                const timeGroup = document.getElementById('time-group');
                timeGroup.style.opacity = '1';
                timeGroup.style.pointerEvents = 'auto';
                
                document.querySelectorAll('.time-slot').forEach(t => t.classList.remove('active'));
                selectedTime = null;
            });

            dateScroll.appendChild(btn);
        }
    }

    // Initialize calendar
    generateCalendar();

    // --- Time Slot Selection ---
    const timeSlots = document.querySelectorAll('.time-slot');
    timeSlots.forEach(slot => {
        slot.addEventListener('click', () => {
            timeSlots.forEach(t => t.classList.remove('active'));
            slot.classList.add('active');
            selectedTime = slot.textContent;
        });
    });

    // --- Form Submission ---
    const form = document.getElementById('booking-form');
    form.addEventListener('submit', (e) => {
        e.preventDefault();
        
        // Find the selected service text instead of just value
        const serviceSelect = document.getElementById('service-select');
        const serviceVal = serviceSelect.value;
        const serviceText = serviceSelect.options[serviceSelect.selectedIndex].text;
        
        const t = translations[currentLang];
        
        if (!serviceVal) {
            showModal(t.err_title, t.err_service);
            return;
        }
        if (!selectedDate || !selectedTime) {
            showModal(t.err_title, t.err_datetime);
            return;
        }

        const dateStr = `${selectedDate.getDate()}/${selectedDate.getMonth() + 1}`;
        const messageHtml = `
            <strong>${t.msg_service}</strong> ${serviceText}<br>
            <strong>${t.msg_date}</strong> ${dateStr}<br>
            <strong>${t.msg_time}</strong> ${selectedTime}<br><br>
            ${t.msg_confirm}
        `;
        showModal(translations[currentLang].modal_title, messageHtml);
    });

    // --- Modal Logic ---
    const modal = document.getElementById('booking-modal');
    const modalCloseBtn = document.getElementById('modal-close-btn');
    const modalOkBtn = document.getElementById('modal-ok-btn');
    const modalBody = document.getElementById('modal-body-content');
    const modalTitle = modal.querySelector('.modal-header h3');

    function showModal(title, content) {
        modalTitle.textContent = title;
        modalBody.innerHTML = content;
        modal.classList.add('show');
    }

    function hideModal() {
        modal.classList.remove('show');
    }

    modalCloseBtn.addEventListener('click', hideModal);
    modalOkBtn.addEventListener('click', hideModal);

    window.addEventListener('click', (e) => {
        if (e.target === modal) {
            hideModal();
        }
    });
});
